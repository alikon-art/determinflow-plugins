def _expected_relation_kind(relation: str) -> str:
    if relation.startswith(("idx_", "uq_")):
        return "i"
    return "r"


def plugin_root(root: Path | None = None) -> Path:
    return root.resolve() if root else Path(__file__).resolve().parents[2]


def catalog_for(family: Family, root: Path | None = None) -> list[MigrationSpec]:
    if family != "novel":
        raise ValueError(f"unsupported migration family: {family}")
    directory = plugin_root(root) / "resources" / "migrations"
    return [
        MigrationSpec(
            family="novel",
            migration_id=migration_id,
            path=directory / f"{migration_id}.sql",
            relations=frozenset(relations),
            columns=frozenset(columns),
            absent_columns=frozenset(absent_columns),
            column_signatures=frozenset(_COLUMN_SIGNATURES.get(migration_id, ())),
            constraints=frozenset(CONSTRAINT_SIGNATURES.get(migration_id, ())),
            indexes=frozenset(_INDEX_SIGNATURES.get(migration_id, ())),
            relation_signatures=frozenset(
                (relation, _expected_relation_kind(relation))
                for relation in relations
            ),
            defaults=frozenset(DEFAULT_SIGNATURES.get(migration_id, ())),
        )
        for migration_id, relations, columns, absent_columns in _CATALOG["novel"]
    ]
