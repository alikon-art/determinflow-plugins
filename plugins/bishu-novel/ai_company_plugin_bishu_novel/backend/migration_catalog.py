    indexes: frozenset[IndexSignature] = frozenset()
    relation_signatures: frozenset[RelationSignature] = frozenset()
    views: frozenset[ViewSignature] = frozenset()
    defaults: frozenset[DefaultSignature] = frozenset()

    @property
    def checksum_sha256(self) -> str:
        return hashlib.sha256(self.path.read_bytes()).hexdigest()


