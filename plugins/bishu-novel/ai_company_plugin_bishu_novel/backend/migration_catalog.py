@dataclass(frozen=True)
class MigrationSpec:
    family: Family
    migration_id: str
    path: Path
    relations: frozenset[str] = frozenset()
    columns: frozenset[tuple[str, str]] = frozenset()
    absent_columns: frozenset[tuple[str, str]] = frozenset()
    column_signatures: frozenset[ColumnSignature] = frozenset()
